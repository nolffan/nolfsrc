#!/usr/bin/env python3
"""The PS2 string table (LTSR) and the CRes strings the PS2 levels need.

The PS2 release keeps its text in one archive entry per language (hash
0x056BAF9E in LITH_PS2.REZ, no name in the directory), in place of the PC's
CRes.dll string table. Layout (little endian):

  0x00  "LTSR"  u16 0, u16 1 (version?)  u32 count  u32 0
  0x10  count x {u16 id, u16 length (with the NUL), u32 offset (from the file start)}
  ...   the strings, NUL-terminated, Latin-1

The European disc has five copies (directory tables 0/1,6,11,...: English;
2: French; 3: German; 4: Spanish; 5: Italian); the US disc's is English.

  ps2strings.py dump  <src> [lang]                  id<TAB>text, every string
  ps2strings.py rc    <src> <map.txt> <out.rc> [lang]  a STRINGTABLE of the mapped strings
  ps2strings.py remap <map.txt>                     ps2id<TAB>pcid for the IDs that move
  ps2strings.py check <src> <map.txt> <CRes.dll>    each mapped string against the PC CRes.dll

<src> is an LTSR file or LITH_PS2.REZ (then [lang] = en|fr|de|es|it, default en).
<map.txt> is build/ps2/ps2-string-map.txt.
"""
import os, re, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
LTSR_HASH = 0x056BAF9E
LANG_TABLE = {'en': 0, 'fr': 2, 'de': 3, 'es': 4, 'it': 5}


def parse_ltsr(data):
    if data[:4] != b'LTSR':
        raise ValueError('not an LTSR string table')
    n = struct.unpack_from('<I', data, 8)[0]
    out = {}
    for i in range(n):
        sid, ln, off = struct.unpack_from('<HHI', data, 16 + 8 * i)
        out[sid] = data[off:off + ln].rstrip(b'\0').decode('latin-1')
    return out


def load(src, lang='en'):
    with open(src, 'rb') as fh:
        head = fh.read(4)
    if head == b'LTSR':
        return parse_ltsr(open(src, 'rb').read())
    sys.path.insert(0, HERE)
    import ps2rez
    f, hdr, tables = ps2rez.open_rez(src)
    for e in tables[LANG_TABLE[lang]]:
        if e[0] == LTSR_HASH and e[2]:
            f.seek(e[1] * 2048)
            return parse_ltsr(f.read(e[2]))
    raise ValueError('no string table in %s' % src)


def read_map(path):
    """[(ps2id, pcid, kind)] from ps2-string-map.txt."""
    out = []
    for line in open(path):
        line = line.split(';')[0].split('#')[0].strip()
        if not line:
            continue
        a, b, kind = line.split()[:3]
        if '-' in a:
            lo, hi = map(int, a.split('-'))
            out += [(i, i, kind) for i in range(lo, hi + 1)]
        else:
            out.append((int(a), int(b), kind))
    return out


def rc_text(s):
    # PS2 printf formats -> the PC's FormatMessage inserts (FormatString)
    n = [0]
    def ins(m):
        n[0] += 1
        return '%%%d!%s!' % (n[0], m.group(1))
    s = re.sub(r'%([ds])', ins, s)
    s = s.replace('\\', '\\\\').replace('"', '""').replace('\n', '\\n').replace('\t', '\\t')
    return s


def write_rc(strings, mapping, out):
    lines = ['// Generated by build/ps2/ps2strings.py from the PS2 disc\'s string table',
             '// (LITH_PS2.REZ) -- do not edit, not committed. IDs: build/ps2/ps2-string-map.txt.',
             '', 'STRINGTABLE DISCARDABLE', 'BEGIN']
    for ps2, pc, kind in sorted(mapping, key=lambda m: m[1]):
        if ps2 not in strings:
            sys.exit('ps2strings: PS2 string %d missing' % ps2)
        lines.append('    %d "%s"' % (pc, rc_text(strings[ps2])))
    lines += ['END', '']
    with open(out, 'w', encoding='latin-1', newline='\r\n') as fh:
        fh.write('\n'.join(lines))


def load_remap(path=None):
    """{ps2 id: pc id} for the IDs that move (ps2-string-map.txt)."""
    path = path or os.path.join(HERE, 'ps2-string-map.txt')
    return {ps2: pc for ps2, pc, kind in read_map(path) if ps2 != pc}


# the level commands that carry a CRes string ID
CMD_ID = re.compile(r'(?i)(\b(?:objective\s+(?:add|completed|remove)|transmission|missionfailed|missiontext|popup)\s+)(\d+)')


def remap_objects(objs, remap):
    """Rewrite the string IDs of PS2 world objects (ps2world.Obj, .props of
    .name/.value) to the PC's: IDs inside command strings (any string
    property), Intelligence InfoId, and DialogueN. Returns the number changed."""
    n = 0
    for o in objs:
        for p in o.props:
            v = p.value
            if isinstance(v, str):
                if re.match(r'Dialogue\d+$', p.name) and v.strip().isdigit():
                    if int(v) in remap:
                        p.value = str(remap[int(v)])
                        n += 1
                    continue
                nv = CMD_ID.sub(lambda m: m.group(1) + str(remap.get(int(m.group(2)), int(m.group(2)))), v)
                if nv != v:
                    p.value = nv
                    n += 1
            elif p.name == 'InfoId' and isinstance(v, float) and int(v) in remap:
                p.value = float(remap[int(v)])
                n += 1
    return n


def pc_strings(dll):
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(HERE)), 'tools'))
    from rsrcdiff import resources
    out = {}
    for k, v in resources(dll).items():
        if k[0] != 6:
            continue
        o = 0
        for i in range(16):
            n = struct.unpack_from('<H', v, o)[0]
            o += 2
            if n:
                out[(k[1] - 1) * 16 + i] = v[o:o + 2 * n].decode('utf-16-le')
            o += 2 * n
    return out


def main(a):
    if not a:
        sys.exit(__doc__)
    cmd = a[0]
    if cmd == 'dump':
        s = load(a[1], a[2] if len(a) > 2 else 'en')
        for k in sorted(s):
            print('%d\t%r' % (k, s[k]))
    elif cmd == 'rc':
        s = load(a[1], a[4] if len(a) > 4 else 'en')
        write_rc(s, read_map(a[2]), a[3])
    elif cmd == 'remap':
        for ps2, pc, kind in read_map(a[1]):
            if ps2 != pc:
                print('%d\t%d\t%s' % (ps2, pc, kind))
    elif cmd == 'check':
        s, m, pc = load(a[1]), read_map(a[2]), pc_strings(a[3])
        for ps2, new, kind in m:
            print('%5d -> %5d %-9s PC(new id): %-40r PC(ps2 id): %r' % (
                ps2, new, kind, pc.get(new), pc.get(ps2)))
        bad = [new for ps2, new, kind in m if new in pc]
        print('collisions at the new IDs:', bad or 'none')
    else:
        sys.exit(__doc__)


if __name__ == '__main__':
    main(sys.argv[1:])
